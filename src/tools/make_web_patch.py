#!/usr/bin/env python3
"""Make the data file for the web patcher (docs/extrafirmware-patch.js).

The file holds only the bytes that differ between the official v1.02 sp505.prg and the EXTRAfirmware
build (the EXTRAfirmware code, the call sites, the menu/descriptor values, the version string and the
recomputed checksums), plus SHA-256 hashes of the official input and of the expected result.
No BOSS/Roland bytes are included.

usage: make_web_patch.py official.prg extrafirmware.prg docs/extrafirmware-patch.js RELEASE VERSION CHECKSUM
e.g.   make_web_patch.py official/sp505.prg out/sp505.prg docs/extrafirmware-patch.js 2.0.0 2.00 FA9AD007
"""
import sys, hashlib, base64, json

orig_path, new_path, out_path, release, version, checksum = sys.argv[1:7]
o = open(orig_path, 'rb').read(); n = open(new_path, 'rb').read()
assert len(o) == len(n), 'size differs'
runs = []
i = 0
while i < len(o):
    if o[i] != n[i]:
        j = i
        while j < len(o) and o[j] != n[j]:
            j += 1
        runs.append([i, base64.b64encode(n[i:j]).decode()])
        i = j
    else:
        i += 1
# self-check: applying the runs to the official file gives the build
b = bytearray(o)
for off, data in runs:
    d = base64.b64decode(data); b[off:off + len(d)] = d
assert bytes(b) == n
data = {
    'release': release, 'versionScreen': version, 'checksum': checksum,
    'size': len(o),
    'inputSha256': hashlib.sha256(o).hexdigest(),
    'outputSha256': hashlib.sha256(n).hexdigest(),
    'runs': runs,
}
with open(out_path, 'w') as f:
    f.write('// Generated by src/tools/make_web_patch.py. Contains only the EXTRAfirmware changes\n')
    f.write('// (no BOSS/Roland code): [file offset, base64 bytes] runs + expected hashes.\n')
    f.write('window.EXTRAFIRMWARE_PATCH = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print('%s: %d runs, %d changed bytes' % (out_path, len(runs), sum(len(base64.b64decode(d)) for _, d in runs)))
